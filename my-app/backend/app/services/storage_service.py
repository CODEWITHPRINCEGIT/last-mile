"""Local upload storage behind a small replaceable abstraction."""

import logging
from pathlib import Path
from uuid import uuid4

from app.core.config import settings

logger = logging.getLogger(__name__)


def ensure_upload_directory() -> Path:
    settings.upload_path.mkdir(parents=True, exist_ok=True)
    return settings.upload_path


def generated_pdf_filename() -> str:
    return f"{uuid4().hex}.pdf"


def save_upload(content: bytes) -> str:
    filename = generated_pdf_filename()
    path = ensure_upload_directory() / filename
    path.write_bytes(content)
    return filename


def get_upload_path(filename: str) -> Path:
    # Filenames are generated by this service; resolve defensively anyway.
    candidate = (ensure_upload_directory() / Path(filename).name).resolve()
    upload_root = ensure_upload_directory().resolve()
    if upload_root not in candidate.parents:
        raise ValueError("Invalid upload filename")
    return candidate


def delete_upload(filename: str) -> None:
    try:
        get_upload_path(filename).unlink(missing_ok=True)
    except (OSError, ValueError) as exc:
        logger.warning("Could not remove uploaded file: %s", type(exc).__name__)
